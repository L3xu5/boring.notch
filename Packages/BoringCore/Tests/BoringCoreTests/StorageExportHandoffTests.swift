import Foundation
import Testing
@testable import BoringCore

private func exportSandbox() throws -> URL {
    let url = FileManager.default.temporaryDirectory.appendingPathComponent("BoringExportTests-" + UUID().uuidString)
    try FileManager.default.createDirectory(at: url, withIntermediateDirectories: true)
    return url
}
struct StorageExportHandoffTests {
    @Test func synchronousDropHandoffSurvivesSourceRemovalBeforeAsyncRead() async throws {
        let sandbox = try exportSandbox(); defer { try? FileManager.default.removeItem(at: sandbox) }
        let store = try OwnedTemporaryAssetStore(rootURL: sandbox.appendingPathComponent("Owned"))
        let payload = Data("generated bytes".utf8)
        let asset = try await store.create(data: payload, suggestedName: "generated.txt")
        let lease = try await store.acquireLease(for: asset.url)
        let handoff = AssetExportHandoff(store: store, leases: [lease])
        let receiver = try #require(handoff.claimReceiver()) // synchronous onDrop acceptance
        await handoff.sourceEnded(.copied)
        let removed = try await store.remove(at: asset.url) // old source-ended cleanup races parsing
        #expect(!removed)
        await Task.yield()
        #expect(try Data(contentsOf: asset.url) == payload) // delayed destination owns readable bytes
        await receiver.finish(success: true)
        #expect(!FileManager.default.fileExists(atPath: asset.url.path))
    }
    @Test func externalURLExportIsDurableAcrossRowRemovalAndStoreReopen() async throws {
        let sandbox = try exportSandbox(); defer { try? FileManager.default.removeItem(at: sandbox) }
        let root = sandbox.appendingPathComponent("Owned")
        let store = try OwnedTemporaryAssetStore(rootURL: root)
        let asset = try await store.create(data: Data([1, 2, 3]), suggestedName: "export.bin")
        let lease = try await store.acquireLease(for: asset.url)
        let handoff = AssetExportHandoff(store: store, leases: [lease])
        await handoff.sourceEnded(.copied)
        #expect(await store.isDurableExport(asset.url))
        #expect(try await !store.remove(at: asset.url))
        let reopened = try OwnedTemporaryAssetStore(rootURL: root)
        #expect(try await !reopened.remove(at: asset.url))
        #expect(try Data(contentsOf: asset.url) == Data([1, 2, 3]))
        #expect(try await reopened.discardExport(at: asset.url))
    }
    @Test func cancelledReceiverKeepsSourceRowAndDataAndReleasesItsLease() async throws {
        let sandbox = try exportSandbox(); defer { try? FileManager.default.removeItem(at: sandbox) }
        let store = try OwnedTemporaryAssetStore(rootURL: sandbox.appendingPathComponent("Owned"))
        let asset = try await store.create(data: Data([7]), suggestedName: "keep")
        let lease = try await store.acquireLease(for: asset.url)
        let result = CallbackResult<Bool>()
        let handoff = AssetExportHandoff(store: store, leases: [lease]) { result.resume(returning: $0) }
        let receiver = try #require(handoff.claimReceiver())
        await handoff.sourceEnded(.copied)
        await receiver.finish(success: false)
        let mayRemove = await withCheckedContinuation { result.install($0) }
        #expect(!mayRemove)
        #expect(FileManager.default.fileExists(atPath: asset.url.path))
        #expect(try await store.remove(at: asset.url)) // no leaked handoff lease
    }
    @Test func receiverMayCompleteBeforeSourceDragEnds() async throws {
        let result = CallbackResult<Bool>()
        let handoff = AssetExportHandoff(store: nil, leases: []) { result.resume(returning: $0) }
        let receiver = try #require(handoff.claimReceiver())
        await receiver.finish(success: true)
        await handoff.sourceEnded(.copied)
        let mayRemove = await withCheckedContinuation { result.install($0) }
        #expect(mayRemove)
    }
}
